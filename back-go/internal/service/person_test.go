func TestPersonServiceRepositoryErrors(t *testing.T) {
	for _, wantErr := range []error{model.ErrPersonNotFound, errors.New("database unavailable"), context.Canceled, context.DeadlineExceeded} {
		t.Run(wantErr.Error(), func(t *testing.T) {
			store := stubPersonRepository{
				create: func(context.Context, *model.Person) error { return wantErr },
				list:   func(context.Context, int, int) ([]model.Person, int64, error) { return nil, 0, wantErr },
				get:    func(context.Context, int64) (model.Person, error) { return model.Person{}, wantErr },
			}
			svc := service.NewPersonService(store)
			created, err := svc.Create(context.Background(), service.CreatePersonInput{Firstname: "A", Lastname: "B"})
			if !errors.Is(err, wantErr) || !reflect.DeepEqual(created, service.PersonResponse{}) {
				t.Fatalf("Create = %+v, %v, want zero response and %v", created, err, wantErr)
			}
			listed, err := svc.List(context.Background(), 1, 10)
			if !errors.Is(err, wantErr) || !reflect.DeepEqual(listed, service.PersonListResponse{}) {
				t.Fatalf("List = %+v, %v, want zero response and %v", listed, err, wantErr)
			}
			fetched, err := svc.GetByID(context.Background(), 42)
			if !errors.Is(err, wantErr) || !reflect.DeepEqual(fetched, service.PersonResponse{}) {
				t.Fatalf("GetByID = %+v, %v, want zero response and %v", fetched, err, wantErr)
			}
		})
	}
}
