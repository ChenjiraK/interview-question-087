type stubPersonRepository struct {
	create func(context.Context, *model.Person) error
	list   func(context.Context, int, int) ([]model.Person, int64, error)
	get    func(context.Context, int64) (model.Person, error)
}

func (s stubPersonRepository) Create(ctx context.Context, value *model.Person) error {
	return s.create(ctx, value)
}

func (s stubPersonRepository) List(ctx context.Context, limit, offset int) ([]model.Person, int64, error) {
	return s.list(ctx, limit, offset)
}

func (s stubPersonRepository) GetByID(ctx context.Context, id int64) (model.Person, error) {
	return s.get(ctx, id)
}

func ptr[T any](value T) *T { return &value }

func assertValidationError(t *testing.T, err error, message string) {
	t.Helper()
	var validationError *service.ValidationError
	if !errors.As(err, &validationError) || validationError.Error() != message {
		t.Fatalf("error = %v, want ValidationError(%q)", err, message)
	}
}

func TestPersonServiceCreate(t *testing.T) {
	for _, test := range []struct {
		name     string
		birthday *string
		address  *string
	}{
		{name: "nullable fields"},
		{name: "leap day and Thai address", birthday: ptr("2000-02-29"), address: ptr("กรุงเทพมหานคร")},
		{name: "empty address is preserved", address: ptr("")},
	} {
		t.Run(test.name, func(t *testing.T) {
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			createdAt := time.Date(2026, 10, 22, 10, 0, 0, 0, time.UTC)
			updatedAt := createdAt.Add(time.Hour)
			calls := 0
			store := stubPersonRepository{create: func(gotCtx context.Context, value *model.Person) error {
				calls++
				if gotCtx != ctx {
					t.Fatal("request context was not forwarded")
				}
				if value.Firstname != "สมชาย" || value.Lastname != "ใจดี" || !reflect.DeepEqual(value.Address, test.address) {
					t.Fatalf("unexpected normalized model: %+v", value)
				}
				if value.ID != 0 || !value.CreatedAt.IsZero() || !value.UpdatedAt.IsZero() {
					t.Fatal("ID and timestamps must be generated by the repository")
				}
				if test.birthday == nil {
					if value.Birthday != nil {
						t.Fatal("omitted birthday must remain nil")
					}
				} else if value.Birthday == nil || value.Birthday.Format(time.DateOnly) != *test.birthday {
					t.Fatalf("birthday was not parsed: %v", value.Birthday)
				}
				value.ID, value.CreatedAt, value.UpdatedAt = 42, createdAt, updatedAt
				return nil
			}}
			got, err := service.NewPersonService(store).Create(ctx, service.CreatePersonInput{
				Firstname: " \tสมชาย\n", Lastname: " ใจดี ", Birthday: test.birthday, Address: test.address,
			})
			want := service.PersonResponse{ID: 42, Firstname: "สมชาย", Lastname: "ใจดี",
				Birthday: test.birthday, Address: test.address, CreatedAt: createdAt, UpdatedAt: updatedAt}
			if err != nil || !reflect.DeepEqual(got, want) || calls != 1 {
				t.Fatalf("Create = %+v, %v (calls=%d), want %+v", got, err, calls, want)
			}
		})
	}
}

func TestPersonServiceCreateValidation(t *testing.T) {
	for _, test := range []struct {
		name    string
		input   service.CreatePersonInput
		message string
	}{
		{"missing firstname", service.CreatePersonInput{Lastname: "B"}, "firstname and lastname are required"},
		{"missing lastname", service.CreatePersonInput{Firstname: "A"}, "firstname and lastname are required"},
		{"blank firstname", service.CreatePersonInput{Firstname: " \t\n", Lastname: "B"}, "firstname and lastname are required"},
		{"blank lastname", service.CreatePersonInput{Firstname: "A", Lastname: "\u2003 "}, "firstname and lastname are required"},
		{"impossible date", service.CreatePersonInput{Firstname: "A", Lastname: "B", Birthday: ptr("2025-02-29")}, "birthday must be a valid date in YYYY-MM-DD format"},
		{"timestamp", service.CreatePersonInput{Firstname: "A", Lastname: "B", Birthday: ptr("2000-01-01T00:00:00Z")}, "birthday must be a valid date in YYYY-MM-DD format"},
		{"empty date", service.CreatePersonInput{Firstname: "A", Lastname: "B", Birthday: ptr("")}, "birthday must be a valid date in YYYY-MM-DD format"},
	} {
		t.Run(test.name, func(t *testing.T) {
			store := stubPersonRepository{create: func(context.Context, *model.Person) error {
				t.Fatal("invalid input reached repository")
				return nil
			}}
			got, err := service.NewPersonService(store).Create(context.Background(), test.input)
			assertValidationError(t, err, test.message)
			if !reflect.DeepEqual(got, service.PersonResponse{}) {
				t.Fatalf("response = %+v, want zero value", got)
			}
		})
	}
}

func TestPersonServiceList(t *testing.T) {
	birthday := time.Date(2000, 2, 29, 15, 0, 0, 0, time.FixedZone("ICT", 7*60*60))
	createdAt := time.Date(2026, 10, 22, 10, 0, 0, 0, time.UTC)
	person := model.Person{ID: 42, Firstname: "A", Lastname: "B", Birthday: &birthday,
		Address: ptr("Bangkok"), CreatedAt: createdAt, UpdatedAt: createdAt.Add(time.Hour)}
	wantPerson := service.PersonResponse{ID: 42, Firstname: "A", Lastname: "B", Birthday: ptr("2000-02-29"),
		Address: ptr("Bangkok"), CreatedAt: person.CreatedAt, UpdatedAt: person.UpdatedAt}
	for _, test := range []struct {
		name        string
		page, limit int
		total       int64
		values      []model.Person
		totalPages  int64
	}{
		{"empty", 1, 10, 0, nil, 0},
		{"partial page", 2, 2, 5, []model.Person{person}, 3},
		{"exact pages", 2, 2, 4, []model.Person{person}, 2},
		{"beyond last page", 4, 2, 5, nil, 3},
		{"minimum limit", 1, 1, 5, []model.Person{person}, 5},
		{"maximum limit", 1, 100, 5, []model.Person{person}, 1},
		{"large total does not overflow", 1, 100, 1<<63 - 1, nil, 92233720368547759},
	} {
		t.Run(test.name, func(t *testing.T) {
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			calls := 0
			store := stubPersonRepository{list: func(gotCtx context.Context, limit, offset int) ([]model.Person, int64, error) {
				calls++
				if gotCtx != ctx || limit != test.limit || offset != (test.page-1)*test.limit {
					t.Fatalf("wrong repository arguments: limit=%d offset=%d context=%v", limit, offset, gotCtx)
				}
				return test.values, test.total, nil
			}}
			got, err := service.NewPersonService(store).List(ctx, test.page, test.limit)
			want := service.Pagination{Page: test.page, Limit: test.limit, Total: test.total, TotalPages: test.totalPages}
			if err != nil || got.Pagination != want || got.Data == nil || len(got.Data) != len(test.values) || calls != 1 {
				t.Fatalf("List = %+v, %v (calls=%d), want pagination %+v and %d people", got, err, calls, want, len(test.values))
			}
			if len(got.Data) > 0 && !reflect.DeepEqual(got.Data[0], wantPerson) {
				t.Fatalf("mapped person = %+v, want %+v", got.Data[0], wantPerson)
			}
		})
	}
}

